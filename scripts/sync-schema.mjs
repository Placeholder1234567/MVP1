// Builds src/lib/sync/schema.ts (the PowerSync client schema) from the columns
// each sync stream selects (powersync/sync-config.yaml) and their Postgres
// types (the Drizzle snapshot), so the device schema can't drift from either.
//   node scripts/sync-schema.mjs          write the file
//   node scripts/sync-schema.mjs --check  fail if it is out of date (CI)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { buildSyncConfig } from './sync-rules.mjs';

const OUT = 'src/lib/sync/schema.ts';

function latestSnapshot() {
	const files = readdirSync('drizzle/meta')
		.filter((f) => f.endsWith('_snapshot.json'))
		.sort();
	return JSON.parse(readFileSync(`drizzle/meta/${files.at(-1)}`, 'utf8'));
}

// SQLite on the device has three storage classes. Postgres arrays and jsonb
// arrive as JSON text, uuids/dates/times as text, booleans as 0/1 integers.
function powersyncType(pgType) {
	if (pgType.endsWith('[]')) return 'text';
	if (/^(boolean|integer|smallint|bigint|serial)$/.test(pgType)) return 'integer';
	if (/^(real|double precision|numeric)/.test(pgType)) return 'real';
	return 'text';
}

export function buildClientSchema() {
	const tables = Object.fromEntries(
		Object.values(latestSnapshot().tables).map((t) => [t.name, t.columns])
	);
	const selected = new Map();
	for (const m of buildSyncConfig().matchAll(/SELECT (.+?) FROM ([a-z_]+)$/gm)) {
		const [, cols, table] = m;
		if (!selected.has(table)) selected.set(table, new Set());
		for (const c of cols.split(',').map((s) => s.trim())) selected.get(table).add(c);
	}
	const lines = [
		'// Generated by scripts/sync-schema.mjs from powersync/sync-config.yaml and the',
		'// Drizzle snapshot. Do not edit: change offline-sync.md §4 or schema.ts, then',
		'// run npm run sync:rules.',
		"import { column, Schema, Table } from '@powersync/web';",
		''
	];
	const names = [...selected.keys()].sort();
	for (const table of names) {
		const pg = tables[table];
		if (!pg) throw new Error(`sync config reads unknown table ${table}`);
		const cols = [...selected.get(table)].filter((c) => c !== 'id'); // PowerSync adds id itself
		lines.push(`const ${table} = new Table({`);
		for (const c of cols) {
			if (!pg[c]) throw new Error(`sync config reads unknown column ${table}.${c}`);
			lines.push(`\t${c}: column.${powersyncType(pg[c].type)},`);
		}
		lines.push('});', '');
	}
	lines.push(`export const syncedTables = { ${names.join(', ')} };`, '');
	lines.push('export const AppSchema = new Schema(syncedTables);', '');
	lines.push("export type Database = (typeof AppSchema)['types'];", '');
	return lines.join('\n');
}

if (process.argv[1]?.endsWith('sync-schema.mjs')) {
	const out = buildClientSchema();
	if (process.argv.includes('--check')) {
		const current = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
		if (current !== out) {
			console.error(`${OUT} is out of date. Run: npm run sync:rules`);
			process.exit(1);
		}
		console.log(`${OUT}: up to date`);
	} else {
		writeFileSync(OUT, out);
		console.log(`${OUT}: written`);
	}
}
